import assert from 'node:assert/strict';
import { createClient } from '@supabase/supabase-js';
if(process.env.CUSTOMER_HUB_LOCAL_VERIFIED!=='1'||process.env.SUPABASE_URL!=='http://127.0.0.1:55421')throw new Error('Verified local Customer Hub runner required');
const db=createClient(process.env.SUPABASE_URL,process.env.SUPABASE_SERVICE_ROLE_KEY,{auth:{persistSession:false}});
const read=async(query)=>{const result=await query;if(result.error)throw result.error;return result.data;};
const memberships=await read(db.from('loyalty_memberships').select('id,user_id,status,tax_code').like('membership_code','MOVI-HUB-%').order('membership_code'));
assert.equal(memberships.length,6);
assert.equal(new Set(memberships.map(row=>row.user_id)).size,6,'fixture membership cardinality');
const userIds=memberships.map(row=>row.user_id);
const certificates=await read(db.from('medical_certificates').select('user_id,status,expiry_date,uploaded_at').in('user_id',userIds).order('uploaded_at',{ascending:false}));
const byUser=new Map();
for(const certificate of certificates)byUser.set(certificate.user_id,[...(byUser.get(certificate.user_id)??[]),certificate]);
const today=new Date().toISOString().slice(0,10),days=(expiry)=>Math.floor((Date.parse(today+'T00:00:00Z')-Date.parse(expiry+'T00:00:00Z'))/86400000);
const approvedState=(letter)=>{
 const membership=memberships.find(row=>row.id.endsWith(String('ABCDEFG'.indexOf(letter)+1).padStart(12,'0')));
 const approved=(byUser.get(membership.user_id)??[]).find(row=>row.status==='approved');
 if(!approved)return 'pending_review';
 const expired=days(approved.expiry_date);
 return expired<=0?'active':expired<=60?'grace_period':'standby';
};
assert.equal(approvedState('A'),'active');
assert.equal(approvedState('B'),'grace_period');
assert.equal(approvedState('C'),'standby');
assert.equal(approvedState('D'),'standby');
assert.equal(approvedState('E'),'active');
assert.equal(approvedState('G'),'pending_review');
const dMembership=memberships.find(row=>row.id.endsWith('000000000004'));
assert.ok((byUser.get(dMembership.user_id)??[]).some(row=>row.status==='pending_review'),'D replacement stays pending');
const redemption=await read(db.from('reward_redemptions').select('id,status').eq('id','c7008000-0000-4000-8000-000000000001').maybeSingle());
assert.ok(redemption);
const buckets=await read(db.storage.listBuckets());
const bucket=buckets.find(item=>item.name==='medical-certificates');
assert.ok(bucket,'medical certificate bucket exists');
assert.equal(bucket.public,false,'medical certificate bucket must remain private');
console.log('Customer Hub local acceptance passed: active, grace, standby, pending replacement, reactivated, initial pending, redemption, private bucket.');
